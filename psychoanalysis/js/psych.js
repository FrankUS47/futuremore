/* psych.js — 心理學部分：紫微星曜描述、由命盤推估的大五人格「傾向」、發展階段 */
(function (g) {
  const PA = g.PA = g.PA || {};

  const TRAIT_NAME = { E: '外向性', A: '親和性', C: '盡責性', ES: '情緒穩定性', O: '開放性' };
  const level = v => v <= 3.5 ? 'low' : v >= 4.8 ? 'high' : 'mid';
  const LV_NAME = { low: '偏低', mid: '中間', high: '偏高' };

  const TEXT = {
    E: { high: '從人群與互動中獲得能量，主動、表達直接；要留意傾聽與獨處充電。', mid: '能在社交與獨處之間切換，視情境調整。', low: '偏好安靜、深度的互動，獨處恢復精力。' },
    A: { high: '體貼、願意合作，人際和諧；要練習清楚說「不」。', mid: '能在合作與堅持立場之間取得平衡。', low: '直接、重視邏輯與公平，敢於提出異議。' },
    C: { high: '有條理、可靠、目標導向；留意完美主義。', mid: '需要時能自律，有時會拖延；小目標與固定流程會更穩。', low: '彈性、隨興，易分心或拖延；建議用「習慣迴路」建立節奏。' },
    ES: { high: '面對壓力相對冷靜、恢復快。', mid: '情緒起伏屬一般範圍，壓力大時需要睡眠、運動與傾訴管道。', low: '情緒較敏感，易焦慮或反覆思考；可練習呼吸放鬆與規律睡眠。' },
    O: { high: '好奇心強、喜歡新點子與抽象思考；要把想法落實。', mid: '能兼顧創新與務實。', low: '務實、重視經驗與穩定。' }
  };

  const STAR_TEXT = {
    紫微: '重尊嚴與位置感，有領導與統整傾向，自尊心強', 天機: '思考敏捷、愛分析規劃，心思細膩、點子多但易多慮',
    太陽: '熱情外放、愛付出，重責任與名聲，容易操心', 武曲: '果斷務實、重效率與結果，態度偏剛直',
    天同: '溫和知足、隨和愛享受，遇事偏求安逸、易依賴', 廉貞: '情感與企圖心都強，重原則，個性多面向',
    天府: '穩重保守、善於累積與經營，包容力佳', 太陰: '細膩內斂、重感受與家庭，情緒敏感',
    貪狼: '多才多藝、好奇心與慾望強，善交際', 巨門: '口才與分析力佳，愛追根究柢，疑慮較多',
    天相: '重禮節與公平，擅長輔佐與照顧他人', 天梁: '老成穩重、有原則，愛照顧他人也愛說教',
    七殺: '獨立果決、敢衝敢挑戰，較孤傲', 破軍: '求變、破舊立新，行動力強但不安於現狀'
  };
  // 各星對應的人格面向（E 外向、A 親和、C 盡責、N 情緒敏感、O 開放；+ 偏高、- 偏低）
  const STAR_TRAIT = {
    紫微: { E: '+', C: '+' }, 天機: { O: '+', N: '+' }, 太陽: { E: '+', A: '+' }, 武曲: { C: '+', A: '-' },
    天同: { A: '+', C: '-', N: '-' }, 廉貞: { N: '+', E: '+' }, 天府: { C: '+', N: '-' }, 太陰: { N: '+', E: '-', A: '+' },
    貪狼: { E: '+', O: '+' }, 巨門: { N: '+', A: '-' }, 天相: { A: '+', C: '+' }, 天梁: { A: '+', C: '+' },
    七殺: { A: '-', E: '+' }, 破軍: { O: '+', C: '-' }
  };

  // 由命宮主星、十神群組與五行平衡推估人格傾向（象徵對應，僅供自我反思）；F 為 PA.facts 的結果
  function chartTraits(F) {
    const t = { E: 4, A: 4, C: 4, ES: 4, O: 4 }, gp = F.gp;
    F.P('命宮').main.forEach(s => {
      const m = STAR_TRAIT[s.n] || {};
      Object.keys(m).forEach(k => {
        const dlt = m[k] === '+' ? 1 : -1;
        if (k === 'N') t.ES -= dlt; else t[k] += dlt;
      });
    });
    if (gp('食傷') >= 25) t.O += 1;
    if (gp('官殺') >= 25) t.C += 1;
    if (gp('印星') >= 25) { t.O += 0.5; t.A += 0.5; }
    if (gp('比劫') >= 25) { t.E += 0.5; t.A -= 0.5; }
    if (gp('財星') >= 25) t.C += 0.5;
    const el = Object.values(F.an.pctAdj);
    if (Math.max(...el) - Math.min(...el) > 30) t.ES -= 0.5;
    Object.keys(t).forEach(k => { t[k] = Math.max(1, Math.min(7, t[k])); });
    return t;
  }

  function stage(age) {
    if (age < 13) return { name: '學齡兒童期', task: '勤奮對自卑：在學習與遊戲中累積「我做得到」的經驗。' };
    if (age < 18) return { name: '青少年期', task: '自我認同對角色混淆：探索「我是誰、我想成為誰」，同儕與學業壓力同時增加。' };
    if (age < 26) return { name: '成年初顯期', task: '探索志向與建立親密關係，在獨立與依附之間找到平衡。' };
    if (age < 41) return { name: '成年早期', task: '親密對孤立、事業定位：建立穩定關係與專業路徑。' };
    if (age < 61) return { name: '成年中期', task: '生產對停滯：傳承、栽培他人並重新調整價值排序。' };
    return { name: '成年晚期', task: '統整對絕望：回顧生命、整合意義。' };
  }

  Object.assign(PA, { TRAIT_NAME, level, LV_NAME, PSY_TEXT: TEXT, STAR_TEXT, STAR_TRAIT, chartTraits, stage });
})(typeof window !== 'undefined' ? window : globalThis);
